def test_overlay_endpoint_returns_bounded_georeferenced_png(client):
    geotiff_id = "geotiff/ethiopia_week1_2_2026-05-01_rainfall_total_median.tif"
    resp = client.get(f"/overlay/{geotiff_id}")
    assert resp.status_code == 200
    body = resp.json()
    assert len(body["bounds"]) == 4
    minlon, minlat, maxlon, maxlat = body["bounds"]
    assert maxlat > minlat  # north-up: catches the export_geotiff orientation bug if it regresses
    assert maxlon > minlon
    assert len(body["png_base64"]) > 100


def test_overlay_endpoint_rejects_non_geotiff_products(client):
    non_tif = "maps/ethiopia_week1_2_2026-05-01_rainfall_total.png"
    resp = client.get(f"/overlay/{non_tif}")
    assert resp.status_code == 400
