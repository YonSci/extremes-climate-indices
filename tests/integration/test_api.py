def test_forecast_calculate_and_poll_status(client, tmp_path, monkeypatch):
    monkeypatch.setenv("EXTREMES_OUTPUT_DIR", str(tmp_path))
    resp = client.post("/forecast/calculate", json={
        "region": "ethiopia", "forecast_dataset": "seas5_operational_2026", "observation_dataset": "chirps_obs",
        "init_date": "2026-05-01", "period_type": "sub_seasonal", "period": "week1_2", "index": "rainfall_total",
        "climatology_period": "obs_1993_2025",
    })
    assert resp.status_code == 200
    job_id = resp.json()["job_id"]
    assert resp.json()["status"] in ("pending", "running", "completed")

    import time
    for _ in range(60):
        status_resp = client.get(f"/forecast/status/{job_id}")
        assert status_resp.status_code == 200
        status = status_resp.json()
        if status["status"] in ("completed", "failed"):
            break
        time.sleep(1)

    assert status["status"] == "completed", status.get("error")
    assert "map" in status["result"]["outputs"]

    map_product_id = status["result"]["outputs"]["map"]
    map_resp = client.get(f"/maps/{map_product_id}")
    assert map_resp.status_code == 200
    assert map_resp.headers["content-type"].startswith("image/")


